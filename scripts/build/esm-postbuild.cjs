#!/usr/bin/env node
/**
 * Post-build step for the ES module outputs (v2.9.1).
 *
 * Pre-2.9.1 the package could not be imported from native Node ESM:
 * `tsc -p tsconfig.esm.json` (module ES2020 + moduleResolution bundler)
 * emits extensionless relative specifiers (`export { OGM } from './ogm'`),
 * which Node's ESM loader (and webpack's `fullySpecified` mode for
 * `"type": "module"` packages) refuses, so `import { OGM } from 'grafeo-ogm'`
 * threw ERR_MODULE_NOT_FOUND. This script:
 *
 * 1. Rewrites every relative specifier in dist/esm (`.js` and `.d.ts`) to a
 *    fully specified one: `./ogm` -> `./ogm.js`, `./testing` ->
 *    `./testing/index.js`. Bundlers keep consuming this tree-shakeable build
 *    (`module` field, `import` condition), and TypeScript `nodenext`
 *    consumers resolve the declarations through it.
 *
 * 2. Writes dist/node/{index,testing}.mjs: thin ESM wrappers over the CJS
 *    build, selected by the `node` condition under `import`. Node therefore
 *    loads ONE copy of the library whether an app `import`s or `require`s
 *    it — no dual-package hazard (`instanceof OGMError`, the static
 *    `Executor.debug` flag, compiler caches stay shared).
 *
 * It fails the build if a specifier cannot be resolved, or if a wrapper would
 * not expose exactly the CJS entry's runtime exports.
 *
 * Dependency-free on purpose: runs with plain `node` after `tsc`.
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..', '..');
const esmDir = path.join(root, 'dist', 'esm');
const cjsDir = path.join(root, 'dist', 'cjs');
const nodeDir = path.join(root, 'dist', 'node');

/** Entry points exposed through package.json `exports`. */
const ENTRIES = [
  { wrapper: 'index.mjs', cjs: 'index.js' },
  { wrapper: 'testing.mjs', cjs: 'testing/index.js' },
];

const isFile = (p) => {
  try {
    return fs.statSync(p).isFile();
  } catch {
    return false;
  }
};

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (/\.(?:js|d\.ts)$/.test(entry.name)) out.push(full);
  }
  return out;
}

/**
 * Resolve an extensionless relative specifier the way a bundler would and
 * return its fully specified form.
 */
function fullySpecify(file, spec) {
  if (/\.(?:m?js|cjs|json)$/.test(spec)) return spec;
  const isDts = file.endsWith('.d.ts');
  const ext = isDts ? '.d.ts' : '.js';
  const base = spec.replace(/\/+$/, '');
  const target = path.resolve(path.dirname(file), base);
  if (isFile(target + ext)) return `${base}.js`;
  if (isFile(path.join(target, `index${ext}`))) return `${base}/index.js`;
  throw new Error(
    `esm-postbuild: cannot resolve '${spec}' imported from ${path.relative(root, file)}`,
  );
}

// `from '…'` (import/export … from), `import '…'` (side effect) and
// `import('…')` (dynamic import / declaration type queries).
const SPECIFIER =
  /(\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)(['"])(\.{1,2}(?:\/[^'"\n]*)?)\2/g;

function rewriteSpecifiers() {
  let rewritten = 0;
  for (const file of walk(esmDir)) {
    const src = fs.readFileSync(file, 'utf8');
    const out = src.replace(SPECIFIER, (_m, lead, quote, spec) => {
      const fixed = fullySpecify(file, spec);
      if (fixed !== spec) rewritten += 1;
      return `${lead}${quote}${fixed}${quote}`;
    });
    if (out !== src) fs.writeFileSync(file, out);
  }
  return rewritten;
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

function writeNodeWrappers() {
  fs.mkdirSync(nodeDir, { recursive: true });
  for (const { wrapper, cjs } of ENTRIES) {
    const cjsPath = path.join(cjsDir, cjs);
    const names = Object.keys(require(cjsPath))
      .filter((k) => k !== '__esModule' && k !== 'default')
      .sort();
    for (const name of names) {
      if (!IDENTIFIER.test(name))
        throw new Error(`esm-postbuild: export '${name}' of ${cjs} is not an identifier`);
    }
    if (names.length === 0)
      throw new Error(`esm-postbuild: ${cjs} has no runtime exports`);
    const rel = path.relative(nodeDir, cjsPath).split(path.sep).join('/');
    const body = [
      '// Generated by scripts/build/esm-postbuild.cjs — do not edit.',
      '// Node ESM entry: re-exports the CommonJS build so `import` and',
      '// `require` share one module instance (no dual-package hazard).',
      `import cjs from '${rel.startsWith('.') ? rel : `./${rel}`}';`,
      '',
      'export const {',
      ...names.map((n) => `  ${n},`),
      '} = cjs;',
      '',
    ].join('\n');
    fs.writeFileSync(path.join(nodeDir, wrapper), body);
  }
}

const count = rewriteSpecifiers();
writeNodeWrappers();
process.stdout.write(
  `esm-postbuild: fully specified ${count} relative import(s) in dist/esm; wrote dist/node/{${ENTRIES.map((e) => e.wrapper).join(',')}}\n`,
);
